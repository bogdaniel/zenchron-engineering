func manyLines(n int) string { return strings.Repeat("x\n", n) }

func violationPaths(violations []FileSizeViolation) []string {
	paths := make([]string, 0, len(violations))
	for _, v := range violations {
		paths = append(paths, v.Path)
	}
	sort.Strings(paths)
	return paths
}

func TestFileSizePolicyAppliesTheCheckersRulesToAnExactTree(t *testing.T) {
	dir := t.TempDir()
	if err := os.Symlink("big.go", filepath.Join(dir, "link.go")); err != nil {
		t.Fatal(err)
	}
	_, tree := sizeRepo(t, dir, map[string]string{
		"file-size-baseline.tsv":   "base_ok.go\t1100\nbase_over.go\t1100\n",
		"file-size-exceptions.tsv": "exc_ok.go\t1500\treason\nexc_over.go\t1500\treason\n",
		"big.go":                   manyLines(1001),
		"exact_cap.go":             manyLines(1000),
		"base_ok.go":               manyLines(1100),
		"base_over.go":             manyLines(1101),
		"exc_ok.go":                manyLines(1500),
		"exc_over.go":              manyLines(1501),
		"generated.go":             "// Code generated by x; DO NOT EDIT.\n" + manyLines(1200),
		"vendor/v.go":              manyLines(2000),
		"notes.md":                 manyLines(5000),
		"nonl.go":                  strings.Repeat("x\n", 1000) + "x", // 1001 lines, no trailing newline
	}, "fixture")
	commit := mustGit(t, dir, "rev-parse", "HEAD")
	violations, err := CheckFileSizePolicy(dir, commit, tree)
	if err != nil {
		t.Fatal(err)
	}
	if got, want := strings.Join(violationPaths(violations), " "), "base_over.go big.go exc_over.go nonl.go"; got != want {
		t.Fatalf("refused %q, want %q (%+v)", got, want, violations)
	}
	for _, v := range violations {
		switch v.Path {
		case "base_over.go":
			if v.Lines != 1101 || v.Limit != 1100 || v.Source != "baseline ceiling" {
				t.Errorf("%+v", v)
			}
		case "exc_over.go":
			if v.Lines != 1501 || v.Limit != 1500 || v.Source != "exception limit" {
				t.Errorf("%+v", v)
			}
		case "big.go":
			if v.Lines != 1001 || v.Limit != 1000 || v.Source != "hard cap" {
				t.Errorf("%+v", v)
			}
		}
	}
	if clean, err := CheckFileSizePolicy(dir, commit, tree); err != nil || len(clean) == 0 {
		t.Fatalf("the verdict must be repeatable: %v %v", clean, err)
	}
}

// A candidate that edits the manifests to make itself pass is not honoured:
// the limits are read from the base revision.
func TestACandidateCannotRaiseItsOwnLimits(t *testing.T) {
	dir := t.TempDir()
	base, _ := sizeRepo(t, dir, map[string]string{"file-size-baseline.tsv": "", "small.go": "package x\n"}, "base")
	_, candidateTree := sizeRepo(t, dir, map[string]string{
		"file-size-exceptions.tsv": "grown.go\t5000\tsmuggled in by the candidate\n",
		"file-size-baseline.tsv":   "grown.go\t5000\n",
		"grown.go":                 manyLines(3000),
	}, "candidate")
	violations, err := CheckFileSizePolicy(dir, base, candidateTree)
	if err != nil {
		t.Fatal(err)
	}
	if len(violations) != 1 || violations[0].Path != "grown.go" || violations[0].Source != "hard cap" {
		t.Fatalf("the candidate's own limits were honoured: %+v", violations)
	}
}

// An unreadable policy is an error, never an empty, permissive one.
func TestAnUnreadableSizePolicyIsNotAnEmptyOne(t *testing.T) {
	dir := t.TempDir()
	_, tree := sizeRepo(t, dir, map[string]string{"a.go": "package a\n"}, "base")
	if _, err := CheckFileSizePolicy(dir, "0123456789012345678901234567890123456789", tree); err == nil {
		t.Fatal("a missing base revision read as an empty policy")
	}
	malformed := t.TempDir()
	base, malformedTree := sizeRepo(t, malformed, map[string]string{"file-size-baseline.tsv": "only-one-column\n", "a.go": "package a\n"}, "base")
	if _, err := CheckFileSizePolicy(malformed, base, malformedTree); err == nil {
		t.Fatal("a malformed manifest read as an empty policy")
	}
	if _, err := CheckFileSizePolicy(dir, "", tree); err == nil {
		t.Fatal("no base was accepted")
	}
}

// The Go port and scripts/check_file_sizes.py must agree on the same repository.
func TestFileSizePolicyMatchesThePythonChecker(t *testing.T) {
	python, err := exec.LookPath("python3")
	if err != nil {
		t.Skip("python3 is not available")
	}
	script, err := os.ReadFile(filepath.Join("..", "scripts", "check_file_sizes.py"))
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	if err := os.Symlink("big.go", filepath.Join(dir, "link.go")); err != nil {
		t.Fatal(err)
	}
	_, tree := sizeRepo(t, dir, map[string]string{
		"scripts/check_file_sizes.py": string(script),
		"file-size-baseline.tsv":      "base_ok.go\t1100\nbase_over.go\t1100\n",
		"file-size-exceptions.tsv":    "exc_ok.go\t1500\treason\nexc_over.go\t1500\treason\nbase_exc.go\t1400\treason\n",
		"big.go":                      manyLines(1001),
		"exact_cap.go":                manyLines(1000),
		"base_ok.go":                  manyLines(1100),
		"base_over.go":                manyLines(1101),
		"base_exc.go":                 manyLines(1300),
		"exc_ok.go":                   manyLines(1500),
		"exc_over.go":                 manyLines(1501),
		"generated.go":                "# generated, do not edit\n" + manyLines(1200),
		"vendor/v.go":                 manyLines(2000),
		"web/app.tsx":                 manyLines(1002),
		"style.css":                   manyLines(1002),
		"notes.md":                    manyLines(5000),
		"nonl.go":                     strings.Repeat("x\n", 1000) + "x",
		".go":                         manyLines(1500),
	}, "fixture")
	// base_exc.go is in the baseline AND has an exception above its ceiling.
	_ = tree
	command := canonicalSizeChecker(t, python, dir)
	out, _ := command.CombinedOutput()
	var want []string
	for _, line := range strings.Split(string(out), "\n") {
		if strings.HasPrefix(line, "FAIL ") {
			fields := strings.SplitN(line, "'", 3)
			if len(fields) >= 2 {
				want = append(want, fields[1])
			}
		}
	}
	sort.Strings(want)
	commit := mustGit(t, dir, "rev-parse", "HEAD")
	violations, err := CheckFileSizePolicy(dir, commit, mustGit(t, dir, "rev-parse", "HEAD^{tree}"))
	if err != nil {
		t.Fatalf("%v\n%s", err, out)
	}
	if got := strings.Join(violationPaths(violations), " "); got != strings.Join(want, " ") || len(want) == 0 {
		t.Fatalf("Go refused %q, Python refused %q\n%s", got, strings.Join(want, " "), out)
	}
}

func TestFileSizeVerdictRefusesWithBoundEvidenceAndFeedback(t *testing.T) {
	dir := t.TempDir()
	base, _ := sizeRepo(t, dir, map[string]string{"file-size-baseline.tsv": "", "ok.go": "package x\n"}, "base")
	commit, tree := sizeRepo(t, dir, map[string]string{"grown.go": manyLines(1200)}, "candidate")
	verifier := BaselineGoVerifier{ArtifactStore: ArtifactStore{Root: t.TempDir()}}
	request := AssuranceRequest{
		RunID: "run-size", Commit: commit, Tree: tree, CheckoutDir: dir, Attempt: 1,
		Contract: Ref{ID: "contract-run-size", Revision: "1"}, Policy: Ref{ID: "policy", Revision: "7"},
		FileSizePolicyBase: base,
	}
	result, done, err := verifier.fileSizeVerdict(request)
	if err != nil || !done {
		t.Fatalf("done=%v err=%v", done, err)
	}
	if result.Passed || result.FailureClass != FailureVerification {
		t.Fatalf("a refused candidate passed or was misclassified: %+v", result)
	}
	if result.Evidence == nil || result.Evidence.Commit != commit || result.Evidence.Tree != tree || result.Evidence.Contract.ID != "contract-run-size" {
		t.Fatalf("the verdict is not bound to the exact candidate and contract: %+v", result.Evidence)
	}
	if result.ArtifactRef == "" || result.FailureSignature == "" || len(result.Artifacts) == 0 {
		t.Fatalf("no artifact for the remediation agent: %+v", result)
	}
	diagnostic, err := verifier.ArtifactStore.AssuranceDiagnostic(result.ArtifactRef, "run-size")
	if err != nil || !strings.Contains(diagnostic, "grown.go") || !strings.Contains(diagnostic, "1200") || !strings.Contains(diagnostic, "hard cap 1000") {
		t.Fatalf("the agent is not told which file, how long, or the limit: %q (%v)", diagnostic, err)
	}

	// A clean tree is not this verifier's verdict to give: it carries on to the suite.
	mustGit(t, dir, "checkout", "-q", "--detach", base)
	request.Commit, request.Tree = base, mustGit(t, dir, "rev-parse", base+"^{tree}")
	if _, done, err := verifier.fileSizeVerdict(request); done || err != nil {
		t.Fatalf("a clean tree was judged: done=%v err=%v", done, err)
	}
	// And a request that carries no requirement is not checked at all.
	request.Commit, request.Tree, request.FileSizePolicyBase = commit, tree, ""
	if _, done, _ := verifier.fileSizeVerdict(request); done {
		t.Fatal("a contract that does not require the claim was checked")
	}
}

func TestOnlyAContractThatRequiresTheClaimIsChecked(t *testing.T) {
	// The policy package and docs/file-size-policy.md spell the claim this way.
	if FileSizePolicyClaimID != "claim-file-size-policy" {
		t.Fatalf("the recognized claim id changed: %q", FileSizePolicyClaimID)
	}
	without := domain.EngineeringWorkContract{RequiredClaims: map[string]domain.RequiredClaim{"claim-validation": {EvidenceClass: AssuranceEvidenceClass}}}
	if got := fileSizePolicyBase(without, "abc"); got != "" {
		t.Fatalf("a contract compiled without the claim was checked against %q", got)
	}
	with := without
	with.RequiredClaims = map[string]domain.RequiredClaim{FileSizePolicyClaimID: {EvidenceClass: AssuranceEvidenceClass}}
	if got := fileSizePolicyBase(with, "abc"); got != "abc" {
		t.Fatalf("a contract that requires the claim was not checked: %q", got)
	}
}
